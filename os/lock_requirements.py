"""
os.lock_requirements
======================

Writes the MIA OS image's hash-locked Python requirements (FW-01; DEC-0263, DEC-0279;
`docs/mia_os/MIA_OS_FINAL_IMPLEMENTATION_ROADMAP.md` §4): `os/requirements.lock` for MIA's packages and
`os/requirements-build.lock` for the two build tools the three source-only packages need. The image installs both with
pip's `--require-hashes`, so a changed or substituted package fails the build.

    python os/lock_requirements.py          # needs uv on the PATH (pip install uv)

**What goes in.** Every line of `requirements.txt` except `IMAGE_EXCLUDED` (Piper: Zac's Q-108 answer keeps it out
of the image until the repository has a licence), resolved for `PYTHON` on `PLATFORM` (Fedora 45's glibc is newer than
manylinux 2.39, so every wheel built for it runs there). **Why two files.** `SOURCE_ONLY` packages publish no wheel, so
the image builds them; pip would fetch their build tools without checking a hash, so the tools are locked separately,
installed first, and the main install runs with `--no-build-isolation`. Run it again whenever `requirements.txt`
changes: `tests/test_os_image.py` fails until the locks cover it.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements.txt"
LOCK = ROOT / "os" / "requirements.lock"
BUILD_LOCK = ROOT / "os" / "requirements-build.lock"
PYTHON = "3.13"
PLATFORM = "x86_64-manylinux_2_39"
IMAGE_EXCLUDED = {"piper-tts": "GPL-3.0; not bundled until the repository has a licence, Zac's Q-108 answer of 2026-11-18"}
SOURCE_ONLY = ("plaid-python", "http-ece", "srt")  # no wheel published; all three pure Python
BUILD_TOOLS = ("setuptools", "wheel")

HEADER = """# {name}: generated by os/lock_requirements.py (FW-01). Never edit by hand; run that script after changing
# requirements.txt (tests/test_os_image.py fails until you do). For Python {python} on Linux x86-64 ({platform}).
# {what}
"""


def requirement_name(line: str) -> str:
    """The normalised package name a requirements line names ("" for comments and blank lines)."""
    line = line.split("#", 1)[0].strip()
    match = re.match(r"[A-Za-z0-9][A-Za-z0-9._-]*", line)
    return re.sub(r"[-_.]+", "-", match.group(0)).lower() if match else ""


def image_requirements(text: str) -> list[str]:
    """The lines of requirements.txt the image installs: every requirement except `IMAGE_EXCLUDED`."""
    return [line for line in text.splitlines() if requirement_name(line) and requirement_name(line) not in IMAGE_EXCLUDED]


def _compile(uv: str, lines: list[str], out: Path, extra: list[str]) -> str:
    """Runs uv's compile on `lines` and returns the lock's text, without uv's header or its "via" notes (they name a
    temporary file's path)."""
    with tempfile.TemporaryDirectory() as tmp:
        src, dst = Path(tmp) / "in.txt", Path(tmp) / "out.txt"
        src.write_text("\n".join(lines) + "\n", encoding="utf-8")
        subprocess.run([uv, "pip", "compile", str(src), "--python-version", PYTHON, "--python-platform", PLATFORM,
                        "--generate-hashes", "--no-header", "--no-annotate", "--quiet", "-o", str(dst), *extra], check=True)
        return dst.read_text(encoding="utf-8")


def main() -> int:
    """Writes both locks; 1 when uv isn't installed."""
    uv = shutil.which("uv")
    if not uv:
        print("uv isn't on the PATH. Install it (pip install uv) and run this again.")
        return 1
    lines = image_requirements(REQUIREMENTS.read_text(encoding="utf-8"))
    only_binary = ["--only-binary", ":all:"] + [arg for name in SOURCE_ONLY for arg in ("--no-binary", name)]
    LOCK.write_text(HEADER.format(name=LOCK.name, python=PYTHON, platform=PLATFORM,
                                  what="MIA's packages. Built from source (no wheel published): " + ", ".join(SOURCE_ONLY)
                                  + ". Left out: " + "; ".join(f"{k} ({v})" for k, v in IMAGE_EXCLUDED.items()) + ".")
                    + "\n" + _compile(uv, lines, LOCK, only_binary), encoding="utf-8")
    BUILD_LOCK.write_text(HEADER.format(name=BUILD_LOCK.name, python=PYTHON, platform=PLATFORM,
                                        what="The build tools for the source-only packages, installed first so pip never "
                                             "fetches an unchecked one.")
                          + "\n" + _compile(uv, list(BUILD_TOOLS), BUILD_LOCK, ["--only-binary", ":all:"]), encoding="utf-8")
    print(f"Wrote {LOCK.relative_to(ROOT)} and {BUILD_LOCK.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
