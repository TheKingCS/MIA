"""
core.event_catalog
====================

The event catalogue (build plan step 7, the module contract's first piece;
Part 1's gap: "no catalogue of the events modules emit and consume"). Read
from the code itself, never written by hand: every event a file publishes on
the event bus (core/event_bus.py: `events.publish("x", ...)`, or core's
`publish(context, "x", ...)` helper) and every event it subscribes to.

`catalogue()` maps each event to its publishers and subscribers; `orphans()`
are events someone listens for that nothing publishes (a renamed event, or
one only a test raises) and events published that nobody hears (fine, often:
a hook for later). `render()` writes `docs/EVENTS.md`;
tests/test_event_catalog.py checks it's current and that no new listener
waits on an event nothing sends.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDERS = ("core", "modules", "gui", "server")
_PUBLISH = re.compile(r"(?:\.publish\(\s*|\bpublish\(\s*[\w.]+\s*,\s*)\"([a-z][a-z0-9_.]+)\"")
_SUBSCRIBE = re.compile(r"\.subscribe\(\s*\"([a-z][a-z0-9_.]+)\"")


def catalogue(root: Path = ROOT) -> dict[str, dict[str, list[str]]]:
    """event -> {"publishers": [files], "subscribers": [files]}, from the code."""
    out: dict[str, dict[str, set]] = {}
    for folder in FOLDERS:
        for path in sorted((root / folder).rglob("*.py")):
            rel = path.relative_to(root).as_posix()
            text = path.read_text(encoding="utf-8", errors="replace")
            for name in _PUBLISH.findall(text):
                out.setdefault(name, {"publishers": set(), "subscribers": set()})["publishers"].add(rel)
            for name in _SUBSCRIBE.findall(text):
                out.setdefault(name, {"publishers": set(), "subscribers": set()})["subscribers"].add(rel)
    return {k: {"publishers": sorted(v["publishers"]), "subscribers": sorted(v["subscribers"])}
            for k, v in sorted(out.items())}


def orphans(found: dict) -> dict[str, list[str]]:
    return {"unheard": [k for k, v in found.items() if v["publishers"] and not v["subscribers"]],
            "unsent": [k for k, v in found.items() if v["subscribers"] and not v["publishers"]]}


def render(found: dict) -> str:
    lines = ["# Events", "",
             "*Generated by `python -m core.event_catalog` from the code (build plan step 7). Don't edit by hand:",
             "change the code, then regenerate. `tests/test_event_catalog.py` fails when it's out of date.*", "",
             "| Event | Published by | Heard by |", "|---|---|---|"]
    for name, v in found.items():
        lines.append(f"| `{name}` | {', '.join(f'`{p}`' for p in v['publishers']) or '—'} | "
                     f"{', '.join(f'`{s}`' for s in v['subscribers']) or '—'} |")
    gaps = orphans(found)
    lines += ["", f"**Heard but never sent** ({len(gaps['unsent'])}): " + (", ".join(f"`{n}`" for n in gaps["unsent"]) or "none") + ".",
              "", f"**Sent but not heard yet** ({len(gaps['unheard'])}): "
              + (", ".join(f"`{n}`" for n in gaps["unheard"]) or "none") + ".", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    (ROOT / "docs" / "EVENTS.md").write_text(render(catalogue()), encoding="utf-8")
    print("docs/EVENTS.md written")
