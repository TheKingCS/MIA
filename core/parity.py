"""
core.parity
=============

Full use both ways, on every device (DEC-0125, Zac 2026-11-07: "MIA should be
absolutely 100% voice capable but I also want 100% capable for use on the
phone too. Full use when I feel like talking and full use when I don't on all
devices"). This measures it, app by app:

- **voice**: one of her Assistant tools works in the app's areas (or the app
  is reached by voice another way, `VOICE_ELSEWHERE`, each with how);
- **pc**: a screen on the PC (its web page, or its desktop screen);
- **phone**: its web page (the phone shows MIA's web screens);
- **glasses**: a card with a menu on the glasses (core/glasses.py), or it's
  what the glasses already are (the orb is Home and Talk).

Every gap is decided in `work/parity.json`: "todo" (to build, with what it
needs) or "none" (deliberately not, with why, e.g. passwords never by voice).
`tests/test_parity.py` fails on a gap nobody decided about and on a decision
for a gap that's gone, so parity can only grow. `python -m core.parity`
writes `docs/PARITY.md`, the table (a test checks it's current).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parent.parent
DECISIONS = ROOT / "work" / "parity.json"
REPORT = ROOT / "docs" / "PARITY.md"
MODES = ("voice", "pc", "phone", "glasses")

# Reached by voice without a tool in the app's own areas: how.
VOICE_ELSEWHERE = {
    "web_home": "Talk itself: Home is MIA and the chat with her",
    "assistant": "Talk itself",
    "observations": "list_observations (the system area)",
    "diagnostics": "check_my_setup and get_system_health (the system area)",
    "module_browser": "set_app_visibility and set_app_focus (Settings' apps area)",
    "sight": "\"look at this\", \"what am I looking at?\" open Look with the camera (core/sight.py wants_look)",
    "good_news": "quick commands: \"what's the good news?\", \"turn on good news radio\" (core/good_news.py reply)",
}
# Has a web page the sidebar doesn't link as App.page: the gear opens Settings, Settings opens Diagnostics.
PAGE_ELSEWHERE = {"settings": "settings.html", "diagnostics": "diagnostics.html"}
# On the glasses as the glasses themselves: the orb is Home and Talk.
GLASSES_ARE = {"web_home": "the orb is Home", "assistant": "the orb is Talk"}


def desktop_registry():
    """Her Assistant tools exactly as the PC app registers them (core/application.py), without starting Qt."""
    from core.app_context import AppContext
    from core.application import MIAApplication
    from core.config_manager import ConfigManager
    from core.event_bus import EventBus

    app = MIAApplication.__new__(MIAApplication)
    app.context = AppContext(config=ConfigManager(), events=EventBus())
    app.config = app.context.config
    app._register_assistant_actions()
    return app.context.assistant_actions


def matrix(registry) -> list[dict]:
    """Each live app and whether it can be used each way: {id, name, voice, pc, phone, glasses}."""
    from core.glasses import ASKS, NOT_ON_GLASSES, PANELS
    from core.web_surfaces import APPS, RETIRED

    domains: dict[str, int] = {}
    for action in registry._actions.values():
        domains[action.domain] = domains.get(action.domain, 0) + 1
    rows = []
    for app in APPS:
        if app.module_id in RETIRED:
            continue
        rows.append({
            "id": app.module_id, "name": app.name,
            "voice": any(domains.get(d) for d in app.domains) or app.module_id in VOICE_ELSEWHERE,
            "pc": True,  # every app has a PC screen: its web page in the desktop window, or its desktop screen
            "phone": bool(app.page) or app.module_id in PAGE_ELSEWHERE,
            "glasses": app.module_id in GLASSES_ARE or (
                app.module_id not in NOT_ON_GLASSES and bool(PANELS.get(app.module_id) or ASKS.get(app.module_id))),
        })
    return rows


def gaps(rows: list[dict]) -> list[str]:
    """Pure logic. Every app-and-way that can't be used yet, as "app:way"."""
    return [f"{r['id']}:{mode}" for r in rows for mode in MODES if not r[mode]]


def load_decisions(path: Path = DECISIONS) -> dict:
    """What was decided about each gap: {"app:way": {"status": "todo"|"none", "why": ...}}."""
    try:
        return json.loads(path.read_text(encoding="utf-8")).get("gaps", {})
    except (OSError, ValueError):
        return {}


def render(rows: list[dict], decisions: dict) -> str:
    """Pure logic. docs/PARITY.md: the coverage counts, the table, and each gap with its decision."""
    total = len(rows)
    counts = {mode: sum(1 for r in rows if r[mode]) for mode in MODES}
    mark = lambda ok: "yes" if ok else "**no**"  # noqa: E731
    lines = [
        "# Parity: full use both ways, on every device",
        "",
        "*Generated by `python -m core.parity` (core/parity.py, DEC-0125); a test checks it's current. Every gap is",
        "decided in `work/parity.json`: to build, or deliberately not.*",
        "",
        f"Of {total} apps: by voice {counts['voice']}, on the PC {counts['pc']}, on the phone {counts['phone']}, "
        f"on the glasses {counts['glasses']}.",
        "",
        "| App | Voice | PC | Phone | Glasses |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines += [f"| {r['name']} | {mark(r['voice'])} | {mark(r['pc'])} | {mark(r['phone'])} | {mark(r['glasses'])} |"
              for r in rows]
    open_gaps = gaps(rows)
    lines += ["", f"## The {len(open_gaps)} gaps", ""]
    for gap in open_gaps:
        decision = decisions.get(gap, {})
        lines.append(f"- `{gap}`: {decision.get('status', 'undecided')}, {decision.get('why', '')}".rstrip(", "))
    return "\n".join(lines) + "\n"


def main(argv: Optional[list] = None) -> None:
    """Writes docs/PARITY.md from her real tools and screens, without the tool registry's log lines."""
    import logging

    logging.disable(logging.INFO)
    rows = matrix(desktop_registry())
    REPORT.write_text(render(rows, load_decisions()), encoding="utf-8")
    print(f"{REPORT.relative_to(ROOT)} written: {len(gaps(rows))} gaps")


if __name__ == "__main__":
    main()
