"""
core.grants
=============

Every capability's tier, and what a grant check would decide (DEC-0156, proposed; migration phase M4 of
`docs/mia_os/MIA_OS_APPLICATION_REGISTRY.md`; the Living System's G1). **This phase watches and refuses nothing:**
enforcing waits on Zac's approval of DEC-0156.

**A tier** says how far MIA may go with a capability (a tool or an action kind) when the initiative is hers, not the
person's:

- `observe`: it only reads. Always allowed.
- `suggest`: it prepares something for the person to look at (a draft, a plan). Always allowed; nothing leaves and
  nothing is changed that isn't a draft.
- `act_within_grant`: it changes the person's own records and can be undone exactly (Zac's rule: routine things run
  on their own with a precise Undo). On her own initiative, only where the person has granted that capability.
- `act_with_approval`: it pays, buys, sends, publishes, deletes, shares, or changes an account: the person's yes each
  time, whatever was granted (the same kinds `core.taught_skills.always_asks` names: a test keeps the two agreeing,
  so there is one classification).
- `never`: MIA doesn't do it at all on her own initiative.

**Where the tiers are kept:** in each app's manifest (`capabilities.tiers`, one per tool and action kind it claims;
`core/app_registry.py` refuses a capability without one), so adding a tool means deciding its tier. The first ones
were generated by the rules here (`default_tool_tier`, `default_action_tier`) and are hand-kept from then on.

**Outside text:** a tool whose answer carries words from outside MIA (a web page, a search, mail, a feed) is named in
its manifest's `capabilities.outside`. Every one must be handled for the model: framed by `browser_safety.untrusted()`
(`FRAMED_TOOLS`) or listed in `core.tool_loop.OUTSIDE_TOOLS`; a test keeps the lists agreeing.

**The check** (`decide`): pure. Who started it (`person`: they pressed or said it; `mia`: her own initiative, as in a
taught skill's step or something she proposes), the tier, and what's been granted give allowed or not, with why.
A person's own press is always theirs to make. `observe()` is the report-only hook the action contract calls: it
logs and counts what enforcing would have stopped (`report()`), and never raises.

Grants themselves (per person, revocable, on one screen) are the next part and are not built here.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

from core.logger import get_logger

log = get_logger(__name__)

OBSERVE, SUGGEST, WITHIN_GRANT, WITH_APPROVAL, NEVER = TIERS = (
    "observe", "suggest", "act_within_grant", "act_with_approval", "never")
PERSON, MIA = "person", "mia"

# Tools whose answers are framed for the model by browser_safety.untrusted() where they're made (core/browser.py,
# core/online_lookup.py).
FRAMED_TOOLS = frozenset({"browse", "browser_back", "browser_click", "browser_read", "browser_type", "do_browser_task",
                          "look_up_online"})
_SUGGEST_PREFIXES = ("draft_", "propose_", "suggest_", "plan_", "preview_")

_would_refuse: dict = {}  # capability -> how many times enforcing would have stopped it (this run)
_tiers: dict = {}  # capability -> tier, read once from the manifests


@dataclass(frozen=True)
class Decision:
    """What a grant check decides for one capability: whether it may run now, its tier, and why."""
    allowed: bool
    tier: str
    why: str


def default_action_tier(kind: str) -> str:
    """Pure logic. The tier an action kind starts with: the person's yes each time for the kinds that always ask
    (`taught_skills.always_asks`), within a grant for every other change."""
    from core.taught_skills import always_asks

    return WITH_APPROVAL if always_asks(kind) else WITHIN_GRANT


def default_tool_tier(name: str, destructive: bool = False) -> str:
    """Pure logic. The tier a tool starts with: observe when it only reads, suggest when it only drafts, the person's
    yes each time when its name says it pays, sends, deletes or the like (or it's marked destructive), else within a
    grant."""
    from core.main_thread import changes_records
    from core.taught_skills import _TOOL_ALWAYS

    if destructive or _TOOL_ALWAYS.search(name):
        return WITH_APPROVAL
    if not changes_records(name):
        return OBSERVE
    if name.startswith(_SUGGEST_PREFIXES):
        return SUGGEST
    return WITHIN_GRANT


def tiers() -> dict:
    """Every capability's tier, from the manifests ({name: tier}), read once per process."""
    if not _tiers:
        from core import app_registry

        for manifest in app_registry.load().manifests.values():
            _tiers.update(manifest.get("capabilities", {}).get("tiers", {}))
    return _tiers


def tier_of(capability: str) -> Optional[str]:
    """A tool's or action kind's tier, or None when no manifest gives it one."""
    return tiers().get(capability)


def decide(tier: Optional[str], initiator: str, granted: bool = False) -> Decision:
    """Pure logic. Whether a capability of this tier may run now, started by the person or by MIA, with or without a
    standing grant for it (see the module's opening). An unknown tier is treated as needing the person's yes."""
    if initiator == PERSON:
        return Decision(True, tier or WITH_APPROVAL, "the person asked for it")
    if tier in (OBSERVE, SUGGEST):
        return Decision(True, tier, "it only reads" if tier == OBSERVE else "it only prepares something to look at")
    if tier == WITHIN_GRANT:
        return (Decision(True, tier, "the person granted it") if granted
                else Decision(False, tier, "it changes records and there's no grant for it yet"))
    if tier == NEVER:
        return Decision(False, tier, "MIA doesn't do this on her own")
    return Decision(False, tier or WITH_APPROVAL, "it needs the person's yes each time")


def observe(capability: str, initiator: str, granted: bool = False) -> Decision:
    """The report-only hook (see the module's opening): decides, and when enforcing would have stopped it, logs it and
    counts it. Never raises and never stops anything."""
    try:
        decision = decide(tier_of(capability), initiator, granted)
        if not decision.allowed:
            _would_refuse[capability] = _would_refuse.get(capability, 0) + 1
            log.info("Grants (watching only): %s by %s would wait: %s.", capability, initiator, decision.why)
        return decision
    except Exception:  # noqa: BLE001 - watching never breaks the change it watches
        log.exception("Grants: couldn't look at %s", capability)
        return Decision(True, WITH_APPROVAL, "couldn't be checked")


def report() -> dict:
    """What enforcing would have stopped so far this run: {capability: times}."""
    return dict(_would_refuse)
