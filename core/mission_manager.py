    # Objectives
    # ------------------------------------------------------------------

    def add_objective(
        self, mission_id: str, description: str, metric_type: str, target: float,
        assigned_profile_id: Optional[str] = None,
    ) -> Mission:
        mission = self.get_mission(mission_id)
        if mission is None:
            raise ValueError(f"No mission with id '{mission_id}'.")
        if metric_type not in METRIC_TYPES:
            raise ValueError(f"Unknown metric_type '{metric_type}'.")
        mission.objectives.append(Objective(
            description=description, metric_type=metric_type, target=target,
            assigned_profile_id=assigned_profile_id,
        ))
        self._bump_updated_at(mission)
        self._save()
        return mission

    def delete_objective(self, mission_id: str, index: int) -> Mission:
        mission = self.get_mission(mission_id)
        if mission is None:
            raise ValueError(f"No mission with id '{mission_id}'.")
        if not (0 <= index < len(mission.objectives)):
            raise ValueError(f"Mission '{mission_id}' has no objective at index {index}.")
        del mission.objectives[index]
        self._bump_updated_at(mission)
        self._save()
        return mission

    def increment_tally(self, mission_id: str, index: int, delta: float = 1.0) -> Mission:
        mission = self.get_mission(mission_id)
        if mission is None:
            raise ValueError(f"No mission with id '{mission_id}'.")
        if not (0 <= index < len(mission.objectives)):
            raise ValueError(f"Mission '{mission_id}' has no objective at index {index}.")
        objective = mission.objectives[index]
        if objective.metric_type != "tally":
            raise ValueError(f"Objective '{objective.description}' is not a tally-type objective.")
        was_objective_complete = objective.progress >= objective.target
        all_were_complete = self._all_objectives_complete(mission)
        objective.progress += delta
        self._bump_updated_at(mission)
        self._save()

        is_objective_complete = objective.progress >= objective.target
        if not was_objective_complete and is_objective_complete:
            self._notify_objective_completed(mission, objective)
        if not all_were_complete and self._all_objectives_complete(mission):
            self._notify_all_objectives_completed(mission)
        return mission

    def _all_objectives_complete(self, mission: Mission) -> bool:
        """
        Uses is_objective_complete() (not a bare progress>=target check
        here) so a mixed mission — some tally objectives, some
        trip_duration_hours ones — is judged correctly on both metric
        types, not just tally's directly-stored progress.
        """
        if not mission.objectives:
            return False
        return all(
            self.is_objective_complete(mission.mission_id, index) for index in range(len(mission.objectives))
        )

    def _notify_objective_completed(self, mission: Mission, objective: Objective) -> None:
        if self.context.notifications is None:
            return
        self.context.notifications.notify(
            title="\U0001F3C6 Objective complete!",
            message=f"You did it! \"{objective.description}\" is complete on your \"{mission.name}\" mission. Keep it up!",
            level="info",
            source="missions",
        )

    def _notify_all_objectives_completed(self, mission: Mission) -> None:
        if self.context.notifications is None:
            return
        self.context.notifications.notify(
            title="\U0001F3C6 All objectives complete!",
            message=f"Every objective on \"{mission.name}\" is done — amazing work! Ready to mark it complete?",
            level="info",
            source="missions",
        )

    def _notify_mission_completed(self, mission: Mission) -> None:
        if self.context.notifications is None:
            return
        self.context.notifications.notify(
            title="\U0001F389 Mission complete!",
            message=f"\"{mission.name}\" is complete! That's a real achievement — what's next?",
            level="info",
            source="missions",
        )

    def objective_progress(self, mission_id: str, index: int) -> Optional[float]:
        mission = self.get_mission(mission_id)
        if mission is None or not (0 <= index < len(mission.objectives)):
            return None
        objective = mission.objectives[index]
        if objective.metric_type == "trip_duration_hours":
            if mission.trip_id is None:
                return 0.0
            return self._trip_elapsed_hours(mission.trip_id) or 0.0
        if objective.metric_type == "task_done":
            if mission.task_id is None or self.context.tasks is None:
                return 0.0
            task = self.context.tasks.get_task(mission.task_id)
            return 1.0 if (task is not None and task.done) else 0.0
        return objective.progress

    def is_objective_complete(self, mission_id: str, index: int) -> bool:
        mission = self.get_mission(mission_id)
        if mission is None or not (0 <= index < len(mission.objectives)):
            return False
        progress = self.objective_progress(mission_id, index)
        return progress is not None and progress >= mission.objectives[index].target

    # ------------------------------------------------------------------
    # Group quests (2026-09-14) — individual vs. group progress over a
    # Mission with real participant_profile_ids. See Objective.
    # assigned_profile_id's own docstring for the shared-vs-personal
    # split these both read.
    # ------------------------------------------------------------------

    def individual_objective_progress(self, mission_id: str, profile_id: str) -> tuple[int, int]:
        """(completed, total) among objectives assigned SPECIFICALLY to
        `profile_id` — the vision doc's own "Your Contribution: 4/7"
        example. Shared objectives (assigned_profile_id is None) don't
        count here — see group_objective_progress() for those."""
        mission = self.get_mission(mission_id)
        if mission is None:
            return (0, 0)
        indices = [i for i, o in enumerate(mission.objectives) if o.assigned_profile_id == profile_id]
        completed = sum(1 for i in indices if self.is_objective_complete(mission_id, i))
        return (completed, len(indices))

    def group_objective_progress(self, mission_id: str) -> tuple[int, int]:
        """(completed, total) across EVERY objective on this Mission —
        personal and shared alike — the vision doc's own "Household
        Progress: 68%" example."""
        mission = self.get_mission(mission_id)
        if mission is None:
            return (0, 0)
        completed = sum(1 for i in range(len(mission.objectives)) if self.is_objective_complete(mission_id, i))
        return (completed, len(mission.objectives))

    def _trip_elapsed_hours(self, trip_id: str) -> Optional[float]:
        trip = self.context.trips.get_trip(trip_id)
        if trip is None or len(trip.splits) < 2:
            return None
        timestamps = sorted(datetime.fromisoformat(s.logged_at) for s in trip.splits)
        return (timestamps[-1] - timestamps[0]).total_seconds() / 3600.0

    # ------------------------------------------------------------------
    # Auto-assignment — "MIA should assign me missions sometimes"
    # ------------------------------------------------------------------

    def check_for_auto_assignment(self) -> Optional[Mission]:
        """
        Called periodically by core/application.py (same always-alive
        QTimer pattern as `_check_daily_occasions`) — see this module's
        own docstring for the two rules this runs, in priority order.
        Creates and returns at most one auto-assigned Mission per call;
        returns None if neither rule's conditions are currently met.
        """
        mission = self._check_idle_rule()
        if mission is not None:
            return mission
        return self._check_stale_task_rule()

    def _check_idle_rule(self) -> Optional[Mission]:
        if any(m.status == "active" for m in self._missions):
            return None

        mia_assigned = [m for m in self._missions if m.assigned_by == "mia"]
        if mia_assigned:
            most_recent = max(mia_assigned, key=lambda m: m.created_at)
            age_days = (datetime.now() - datetime.fromisoformat(most_recent.created_at)).total_seconds() / 86400.0
            if age_days < _AUTO_ASSIGN_IDLE_DAYS:
                return None

        used_names = {m.name for m in self._missions}
        template = next(
            (t for t in _AUTO_MISSION_TEMPLATES if t[0] not in used_names),
            _AUTO_MISSION_TEMPLATES[0],  # every template's been used before — just cycle back to the first
        )
        name, objective_specs = template
        mission = self.add_mission(name=name, assigned_by="mia")
        for description, metric_type, target in objective_specs:
            self.add_objective(mission.mission_id, description, metric_type, target)
        self._notify_mission_auto_assigned(mission)
        return mission

    def _check_stale_task_rule(self) -> Optional[Mission]:
        if self.context.tasks is None:
            return None

        wrapped_task_ids = {m.task_id for m in self._missions if m.task_id is not None}
        now = datetime.now()
        candidates = [
            task
            for task in self.context.tasks.all_tasks()
            if not task.done and task.task_id not in wrapped_task_ids and task.updated_at
        ]
        if not candidates:
            return None

        stalest = min(candidates, key=lambda t: t.updated_at)
        age_days = (now - datetime.fromisoformat(stalest.updated_at)).total_seconds() / 86400.0
        if age_days < _STALE_TASK_DAYS:
            return None

        mission = self.add_mission(name=f"Finally Finish: {stalest.title}", task_id=stalest.task_id, assigned_by="mia")
        self.add_objective(mission.mission_id, f'Complete "{stalest.title}"', "task_done", 1.0)
        self._notify_mission_auto_assigned(mission)
        return mission

    def _notify_mission_auto_assigned(self, mission: Mission) -> None:
        if self.context.notifications is None:
            return
        self.context.notifications.notify(
            title="\U0001F4DC MIA has a new mission for you",
            message=f"\"{mission.name}\" — accept the challenge, or abandon it if it's not for you right now.",
            level="info",
            source="missions",
        )
