ABANDON_REASONS: tuple[str, ...] = ("too_hard", "not_interested", "no_time", "other")


@dataclass
class Mission:
    mission_id: str
    name: str
    trip_id: Optional[str] = None
    task_id: Optional[str] = None
    # Connective-infrastructure pass (2026-09-11) — a Mission can
    # optionally be the gamified "face" of a Project, rather than the
    # two staying two unrelated containers for structured work. None
    # by default (zero migration needed for existing data/missions.json)
    # and, deliberately, not settable through update_mission() once a
    # Mission exists — same "pick it at creation, don't reassign later"
    # rule trip_id already follows.
    project_id: Optional[str] = None
    status: str = "active"  # "active" | "completed" | "abandoned"
    # The "mission failure/struggle signal" pass (2026-09-11) — why an
    # abandoned mission was abandoned, one of ABANDON_REASONS above (or
    # "" — no reason recorded, e.g. every mission abandoned before this
    # field existed). Only meaningful when status == "abandoned"; see
    # gui/add_edit_mission_dialog.py for how the UI keeps a stray value
    # here from sticking to a mission that isn't actually abandoned.
    abandon_reason: str = ""
    assigned_by: str = "user"  # "user" | "mia" — see module docstring's "2026-07-16 gamification pass"
    objectives: list[Objective] = field(default_factory=list)
    created_at: str = ""  # ISO datetime
    updated_at: str = ""  # ISO datetime
    # 2026-07-18 design handoff (CCH.zip's Mission Log screen) — cosmetic/
    # gamification fields the redesigned Missions module surfaces.
    # `region` is a short mono "eyebrow" label (e.g. "FIELD SEASON ·
    # FISHING"), not a real geographic region — free text, same "just a
    # label" spirit as Trip.activity_type.
    icon: str = "\U0001F4CB"  # clipboard, matches this project's emoji-glyph convention (no image assets)
    region: str = ""
    summary: str = ""  # longer descriptive paragraph, shown on the Mission Log detail card
    difficulty: str = "NORMAL"
    mission_type: str = "OPTIONAL MISSION"  # e.g. "OPTIONAL MISSION", "DAILY MISSION" — free text, shown as-is
    reward_xp: int = 0
    reward_credits: int = 0
    # "My Hero's Path" (2026-09-11) — optional per-skill XP a completed
    # Mission also grants, alongside its existing flat reward_xp, via
    # the same core.gamification.grant_xp() path every routine-
    # completion hook already uses. Empty by default: every Mission
    # created before this pass deserializes with skill_rewards=[] and
    # behaves exactly as it did — no migration needed. Same "a record
    # owns its own nested list of sub-items" shape as `objectives`
    # above, not a separate top-level manager.
    skill_rewards: list[SkillWeight] = field(default_factory=list)
    # "Recipe Unlocked" (2026-09-12) — real core.kitchen_manager.Recipe
    # ids to unlock (Recipe.locked -> False) on this Mission's real
    # completion. Empty by default, zero migration needed. Credited
    # independently of skill_rewards/reward_xp — see
    # MissionManager._unlock_mission_recipes().
    recipe_unlocks: list[str] = field(default_factory=list)
    # Design restyle, Phase 3 (2026-09-12) — the Sensor Monitor screen's
    # "START QUEST" button on a crossed-threshold MaintenanceTask
    # (core.maintenance_manager) needs to find-or-create exactly one
    # Mission per task, same optional-FK shape trip_id already
    # establishes above (picked at creation, not reassignable via
    # update_mission()). None by default — zero migration needed.
    maintenance_task_id: Optional[str] = None
    # "Manage Skills" UI (2026-09-12) — True once this Mission's
    # reward_xp/reward_credits/skill_rewards have been bulk-credited at
    # least once. Real, not speculative: Mission's own status combo
    # (gui/add_edit_mission_dialog.py) lets a user set a completed
    # Mission back to "active" and complete it again — without this
    # flag, that real, reachable cycle would re-grant every reward each
    # time (the same exploit core.project_manager.Project's own
    # skill_weights_credited already guards against — its comment used
    # to claim Mission's status has "no going back," which is wrong).
    # Never reset once True. Doesn't gate add_skill_reward()'s own
    # single-new-weight crediting path — that one's safe by
    # construction (it only ever credits the ONE weight just appended).
    rewards_credited: bool = False
    # Recurring Missions (2026-09-13) — same optional-FK shape as
    # maintenance_task_id above. A Mission created by
    # core.recurring_mission_manager.RecurringMissionManager carries all
    # three: which template it came from, whether it's the "daily"
    # occurrence or the week's "weekly" summary/bonus, and a stable key
    # identifying *which* occurrence (the daily one's real ISO date, or
    # the weekly one's "{start_date}-Wn") so ensure_current_missions()
    # can look up "does this occurrence already exist" without any date
    # parsing of created_at. None for every ordinary Mission.
    recurring_template_id: Optional[str] = None
    recurring_kind: Optional[str] = None  # "daily" | "weekly"
    occurrence_key: Optional[str] = None
    # Mission-to-asset tagging (2026-09-13) — same optional-FK shape as
    # maintenance_task_id above, but pointing at the whole
    # MaintenanceAsset rather than one specific recurring task on it: a
    # Mission can be generally "about" a house/mower/truck/greenhouse
    # asset (e.g. "Clean Out the Old House") without being tied to any
    # one task. Surfaced by gui/widgets/asset_missions_panel.py on
    # whichever real per-area module (Garage/Real Estate/Greenhouse)
    # owns that asset's category.
    maintenance_asset_id: Optional[str] = None
    # Per-profile rewards (2026-09-14) — the user's own ask ("she will
    # obviously have profile specific missions and maybe not have some
    # of the same ones I have too"). None (the default, every existing
    # Mission included) means "shared/unattributed" — counts toward
    # EVERY profile's missions_completed, same as before this field
    # existed. Settable at creation for real forward-planning
    # ("assign this Mission to Faith"); otherwise auto-stamped with
    # whoever's active the moment it's genuinely completed (see
    # update_mission() below) — same "credit whoever's actually active"
    # precedent core.gamification.grant_xp() already follows for XP,
    # so a Mission naturally becomes whoever's real accomplishment
    # completed it, with zero new assignment UI required.
    profile_id: Optional[str] = None
    # Group quests (2026-09-14) — the real party members on this
    # Mission, e.g. "Prepare the House for Fall" with both Zac and
    # Faith. Empty (the default, every existing Mission included) means
    # a normal solo/unattributed Mission — completely unchanged
    # behavior. When non-empty: _credit_mission_rewards() grants the
    # flat reward_xp/reward_credits/skill_rewards to EVERY participant
    # on completion (not just whoever was active), and
    # core.rewards_manager's missions_completed stat counts it for
    # every participant too — "the mission can have... group rewards,"
    # the user's own words.
    participant_profile_ids: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "mission_id": self.mission_id,
            "name": self.name,
            "trip_id": self.trip_id,
            "task_id": self.task_id,
            "project_id": self.project_id,
            "status": self.status,
            "abandon_reason": self.abandon_reason,
            "assigned_by": self.assigned_by,
            "objectives": [o.to_dict() for o in self.objectives],
            "created_at": self.created_at,
            "updated_at": self.updated_at,
            "icon": self.icon,
            "region": self.region,
            "summary": self.summary,
            "difficulty": self.difficulty,
            "mission_type": self.mission_type,
            "reward_xp": self.reward_xp,
            "reward_credits": self.reward_credits,
            "skill_rewards": [{"skill_id": w.skill_id, "xp": w.xp} for w in self.skill_rewards],
            "recipe_unlocks": list(self.recipe_unlocks),
            "maintenance_task_id": self.maintenance_task_id,
            "rewards_credited": self.rewards_credited,
            "recurring_template_id": self.recurring_template_id,
            "recurring_kind": self.recurring_kind,
            "occurrence_key": self.occurrence_key,
            "maintenance_asset_id": self.maintenance_asset_id,
            "profile_id": self.profile_id,
            "participant_profile_ids": list(self.participant_profile_ids),
        }

    @staticmethod
    def from_dict(data: dict) -> "Mission":
        return Mission(
            mission_id=data.get("mission_id", uuid.uuid4().hex[:10]),
            name=data.get("name", ""),
            trip_id=data.get("trip_id"),
            task_id=data.get("task_id"),
            project_id=data.get("project_id"),
            status=data.get("status", "active"),
            abandon_reason=data.get("abandon_reason", ""),
            assigned_by=data.get("assigned_by", "user"),
            objectives=[Objective.from_dict(d) for d in data.get("objectives", [])],
            created_at=data.get("created_at", ""),
            updated_at=data.get("updated_at", ""),
            icon=data.get("icon", "\U0001F4CB"),
            region=data.get("region", ""),
            summary=data.get("summary", ""),
            difficulty=data.get("difficulty", "NORMAL"),
            mission_type=data.get("mission_type", "OPTIONAL MISSION"),
            reward_xp=data.get("reward_xp", 0),
            reward_credits=data.get("reward_credits", 0),
            skill_rewards=[
                SkillWeight(skill_id=d["skill_id"], xp=d["xp"]) for d in data.get("skill_rewards", [])
            ],
            recipe_unlocks=list(data.get("recipe_unlocks", [])),
            maintenance_task_id=data.get("maintenance_task_id"),
            rewards_credited=bool(data.get("rewards_credited", False)),
            recurring_template_id=data.get("recurring_template_id"),
            recurring_kind=data.get("recurring_kind"),
            occurrence_key=data.get("occurrence_key"),
            maintenance_asset_id=data.get("maintenance_asset_id"),
            profile_id=data.get("profile_id"),
            participant_profile_ids=list(data.get("participant_profile_ids", [])),
        )


class MissionManager:
    def __init__(self, context: AppContext) -> None:
        self.context = context
        self._missions: list[Mission] = []
        self._load()

    # ------------------------------------------------------------------
    # Persistence
    # ------------------------------------------------------------------

    def _load(self) -> None:
        if not _MISSIONS_FILE.exists():
            self._missions = []
            return
        try:
            raw = json.loads(_MISSIONS_FILE.read_text(encoding="utf-8"))
            self._missions = [Mission.from_dict(d) for d in raw]
        except (json.JSONDecodeError, OSError):
            log.exception("Failed to load missions.json — starting with an empty list.")
            self._missions = []

    def _save(self) -> None:
        _DATA_DIR.mkdir(parents=True, exist_ok=True)
        _MISSIONS_FILE.write_text(
            json.dumps([m.to_dict() for m in self._missions], indent=2),
            encoding="utf-8",
        )

    def _bump_updated_at(self, mission: Mission) -> None:
        mission.updated_at = datetime.now().isoformat(timespec="seconds")

    # ------------------------------------------------------------------
    # Mission CRUD
    # ------------------------------------------------------------------

    def add_mission(
        self,
        name: str,
        trip_id: Optional[str] = None,
        task_id: Optional[str] = None,
        project_id: Optional[str] = None,
        assigned_by: str = "user",
        icon: str = "\U0001F4CB",
        region: str = "",
        summary: str = "",
        difficulty: str = "NORMAL",
        mission_type: str = "OPTIONAL MISSION",
        reward_xp: int = 0,
        reward_credits: int = 0,
        skill_rewards: Optional[list[SkillWeight]] = None,
        recipe_unlocks: Optional[list[str]] = None,
        maintenance_task_id: Optional[str] = None,
        recurring_template_id: Optional[str] = None,
        recurring_kind: Optional[str] = None,
        occurrence_key: Optional[str] = None,
        maintenance_asset_id: Optional[str] = None,
        profile_id: Optional[str] = None,
        participant_profile_ids: Optional[list[str]] = None,
    ) -> Mission:
        now = datetime.now().isoformat(timespec="seconds")
        mission = Mission(
            mission_id=uuid.uuid4().hex[:10],
            name=name,
            trip_id=trip_id,
            task_id=task_id,
            project_id=project_id,
            assigned_by=assigned_by,
            created_at=now,
            updated_at=now,
            icon=icon,
            region=region,
            summary=summary,
            difficulty=difficulty,
            mission_type=mission_type,
            reward_xp=reward_xp,
            reward_credits=reward_credits,
            skill_rewards=list(skill_rewards) if skill_rewards else [],
            recipe_unlocks=list(recipe_unlocks) if recipe_unlocks else [],
            maintenance_task_id=maintenance_task_id,
            recurring_template_id=recurring_template_id,
            recurring_kind=recurring_kind,
            occurrence_key=occurrence_key,
            maintenance_asset_id=maintenance_asset_id,
            profile_id=profile_id,
            participant_profile_ids=list(participant_profile_ids) if participant_profile_ids else [],
        )
        self._missions.append(mission)
        self._save()
        log.info("Mission added: '%s'", name)
        return mission

    def update_mission(self, mission_id: str, **fields) -> Mission:
        mission = self.get_mission(mission_id)
        if mission is None:
            raise ValueError(f"No mission with id '{mission_id}'.")
        was_completed = mission.status == "completed"
        was_abandoned = mission.status == "abandoned"
        for key, value in fields.items():
            if key in ("created_at", "trip_id", "project_id", "rewards_credited"):
                raise ValueError(f"'{key}' can't be set through update_mission().")
            if not hasattr(mission, key):
                raise ValueError(f"Mission has no field '{key}'.")
            setattr(mission, key, value)
        self._bump_updated_at(mission)
        self._save()
        # Fires uniformly whether "completed" was set via
        # modules/missions/module.py's own UI button or the Assistant's
        # complete_mission action (core/application.py) — celebration
        # logic lives here, in the manager, so neither call site needs
        # its own copy of "did this just newly become complete."
        if not was_completed and mission.status == "completed":
            # Per-profile rewards (2026-09-14) — a Mission created with
            # no explicit owner becomes whoever's real accomplishment
            # completed it, the first time it's genuinely completed
            # (never reassigned on a later re-completion — same "pick
            # it once" rule trip_id/project_id already follow). See
            # Mission.profile_id's own docstring.
            if mission.profile_id is None and self.context.profiles is not None:
                active_profile = self.context.profiles.get_active_profile()
                if active_profile is not None:
                    mission.profile_id = active_profile.profile_id
            self._notify_mission_completed(mission)
            # "Manage Skills" UI (2026-09-12) — reward-crediting
            # specifically (not the notify/recipe-unlock/event-publish
            # below) is additionally gated on rewards_credited: a
            # completed Mission's status can genuinely go back to
            # "active" via gui/add_edit_mission_dialog.py's own status
            # combo, and without this guard re-completing would
            # re-grant every reward every time (a real exploit vector,
            # not theoretical — see Mission.rewards_credited's own
            # docstring). The other three effects below are left firing
            # on every genuine completion transition, unchanged —
            # narrower fix, not a broader behavior change to Pathways/
            # Recipe-unlock semantics that weren't part of this bug.
            if not mission.rewards_credited:
                self._credit_mission_rewards(mission)
                mission.rewards_credited = True
                # A second save — the one above already ran before this
                # block, so without this the flag would only ever live
                # in memory and never actually persist (caught by this
                # feature's own regression test, not assumed correct).
                self._save()
            # "Recipe Unlocked" (2026-09-12) — deliberately a separate
            # call, not folded into _credit_mission_rewards(): that
            # method's own early-return is about profile-XP crediting
            # specifically (no active profile means no one to credit)
            # and must not gate recipe unlocking, which has nothing to
            # do with an active profile existing — Kitchen has no
            # per-profile concept at all.
            self._unlock_mission_recipes(mission)
            # Mission Pathways (2026-09-11) — a real, previously-missing
            # gap this closes independent of that feature: nothing in
            # this codebase reacted to a Mission actually finishing
            # before this. Fires exactly once, on the same real
            # transition as the celebration/reward-crediting above.
            self.context.events.publish("mission.completed", mission_id=mission.mission_id)
        # "Mission failure/struggle signal" (2026-09-11) — same
        # transition-detection shape as mission.completed above, fires
        # once per genuine active/completed -> abandoned transition
        # (and again on a later re-abandon, same re-triggering
        # semantics mission.completed already has). Lets
        # core/discovery_manager.py react to *why* without this module
        # needing to know Discovery exists.
        if not was_abandoned and mission.status == "abandoned":
            self.context.events.publish(
                "mission.abandoned", mission_id=mission.mission_id, reason=mission.abandon_reason
            )
        return mission

    def _credit_mission_rewards(self, mission: Mission) -> None:
        """
        Credits reward_xp/reward_credits to the active profile — best-
        effort, same graceful-degradation stance as everything else here
        that depends on another manager (no active profile yet, e.g.
        during first-run setup, just means no one to credit).

        "My Hero's Path" (2026-09-11): also credits mission.skill_rewards
        to context.skills, if wired — a completed Mission is a real,
        deliberate completion, not routine CRUD, so it always uses its
        own credit-and-notify logic here rather than routing through
        core.gamification.grant_xp() (which would also fire a second,
        redundant notification on top of _notify_mission_completed()'s
        own).

        Group quests (2026-09-14): when `mission.participant_profile_ids`
        is real (non-empty), the SAME flat reward goes to EVERY
        participant, not just whoever happened to be active when the
        mission's last condition completed — "group rewards," the
        user's own words. Falls back to "just the active profile" for
        every mission with no real participants (every Mission before
        this pass, and any ordinary solo Mission still), unchanged.
        """
        if self.context.profiles is None or (
            mission.reward_xp == 0 and mission.reward_credits == 0 and not mission.skill_rewards
        ):
            return
        if mission.participant_profile_ids:
            profile_ids = list(mission.participant_profile_ids)
        else:
            active_profile = self.context.profiles.get_active_profile()
            if active_profile is None:
                return
            profile_ids = [active_profile.profile_id]

        for profile_id in profile_ids:
            if mission.reward_xp:
                self.context.profiles.add_xp(profile_id, mission.reward_xp)
            if mission.reward_credits:
                self.context.profiles.add_credits(profile_id, mission.reward_credits)
            if mission.skill_rewards and self.context.skills is not None:
                for weight in mission.skill_rewards:
                    self.context.skills.add_skill_xp(profile_id, weight.skill_id, weight.xp)

    def _unlock_mission_recipes(self, mission: Mission) -> None:
        """
        "Recipe Unlocked" (2026-09-12) — unlocks every real Recipe
        mission.recipe_unlocks names, via core.kitchen_manager
        .KitchenManager.unlock_recipe() (context.kitchen), which is
        itself idempotent — never fires a duplicate notification for a
        recipe that's already unlocked. Household-wide, not gated on an
        active profile — see this method's own call site in
        update_mission() for why it's kept separate from
        _credit_mission_rewards().
        """
        if not mission.recipe_unlocks or self.context.kitchen is None:
            return
        for recipe_id in mission.recipe_unlocks:
            self.context.kitchen.unlock_recipe(recipe_id)

    def add_skill_reward(self, mission_id: str, skill_id: str, xp: int) -> Mission:
        """Declares (or retroactively adds) a skill this Mission
        rewards — "Manage Skills" UI (2026-09-12), a near-verbatim port
        of core.project_manager.ProjectManager.add_skill_weight(). If
        the Mission is still active, this weight is simply appended and
        gets credited normally when it later completes (see
        update_mission()). If the Mission is ALREADY completed, this
        credits just this one new weight immediately — never the whole
        list, so an earlier completion's already-granted rewards are
        never double-credited. Doesn't touch rewards_credited — safe by
        construction."""
        mission = self.get_mission(mission_id)
        if mission is None:
            raise ValueError(f"No mission with id '{mission_id}'.")
        weight = SkillWeight(skill_id=skill_id, xp=xp)
        mission.skill_rewards.append(weight)
        self._bump_updated_at(mission)
        self._save()
        if mission.status == "completed":
            grant_xp(
                self.context,
                0,
                "\U0001F4DD Skill credited!",
                f"'{mission.name}' also taught you something — crediting it now.",
                skill_weights=[weight],
            )
        return mission

    def delete_mission(self, mission_id: str) -> None:
        self._missions = [m for m in self._missions if m.mission_id != mission_id]
        self._save()

    def get_mission(self, mission_id: str) -> Optional[Mission]:
        for mission in self._missions:
            if mission.mission_id == mission_id:
                return mission
        return None

    def all_missions(self) -> list[Mission]:
        return sorted(self._missions, key=lambda m: m.created_at, reverse=True)

    def missions_for_trip(self, trip_id: str) -> list[Mission]:
        return [m for m in self._missions if m.trip_id == trip_id]

    def missions_for_maintenance_task(self, task_id: str) -> list[Mission]:
        return [m for m in self._missions if m.maintenance_task_id == task_id]

    def missions_for_maintenance_asset(self, asset_id: str) -> list[Mission]:
        return [m for m in self._missions if m.maintenance_asset_id == asset_id]

